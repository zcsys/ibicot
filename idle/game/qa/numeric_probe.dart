import 'dart:convert';
import 'dart:io';
import 'package:tideglass_core/tideglass_core.dart';

BigInt decimal24(String text) {
  final parts = text.toLowerCase().split('e');
  final exponent = parts.length == 2 ? int.parse(parts[1]) : 0;
  final decimal = parts[0].split('.');
  final fraction = decimal.length == 2 ? decimal[1] : '';
  final digits = BigInt.parse('${decimal[0]}$fraction');
  final power = 24 + exponent - fraction.length;
  return power >= 0 ? digits * BigInt.from(10).pow(power) : digits ~/ BigInt.from(10).pow(-power);
}
void main(List<String> args) {
  const engine = TideglassEngine();
  final data = jsonDecode(File(args[0]).readAsStringSync()) as Map<String, dynamic>;
  var checks = 0;
  final failures = <String>[];
  void check(bool ok, String name) { checks++; if(!ok) failures.add(name); }
  for(final item in data['prices'] as List) {
    final tier=item['tier'] as int, owned=item['owned'] as int, q=item['quantity'] as int;
    final expected=BigInt.parse(item['micros']);
    final counts=[100,100,100,100,100]..[tier]=owned;
    final state=GameState(counts: counts,walletMicros:expected,lifetimeMicros:expected);
    check(engine.bulkPriceMicros(tier,owned,q)==expected,'price $tier/$owned/$q');
    final exact=engine.buy(state,tier,q);
    check(exact.accepted && exact.state.walletMicros==BigInt.zero && exact.state.counts[tier]==owned+q,'exact batch $tier/$owned/$q');
    final below=state.copyWith(walletMicros:expected-BigInt.one);
    check(!engine.buy(below,tier,q).accepted,'one micro below $tier/$owned/$q');
  }
  for(final item in data['thresholds'] as List) {
    final charts=BigInt.parse(item['charts']), boundary=BigInt.parse(item['micros']);
    check(engine.prestigeEntitlement(boundary)==charts,'prestige exact $charts');
    check(engine.prestigeEntitlement(boundary-BigInt.one)<charts,'prestige below $charts');
  }
  for(final item in data['rates'] as List) {
    final expected=decimal24(item['output']);
    final state=GameState(counts: List<int>.from(item['counts']),charts:BigInt.parse(item['charts']),lifetimeMicros:BigInt.from(10).pow(120));
    final actual=engine.outputPerSecond(state).raw;
    check((actual-expected).abs()*BigInt.from(10).pow(20)<=expected,'rate ${item['counts']}/${item['charts']}');
  }
  for(final item in data['logs'] as List) {
    final expected=decimal24(item['value']);
    final actual=log2Ratio(BigInt.parse(item['numerator']),BigInt.parse(item['denominator'])).raw;
    check((actual-expected).abs()<=BigInt.from(10000),'log ${item['numerator']}/${item['denominator']}');
  }
  print(jsonEncode({'source':'independent mathematical oracle generated by Python Fraction/Decimal','checks':checks,'passed':failures.isEmpty,'failures':failures,'output_relative_tolerance':'1e-20','log_absolute_tolerance':'1e-20','discrete_tolerance':0}));
  if(failures.isNotEmpty) exitCode=1;
}
