"""Pin the bundled gameplay content; this does not approve release content."""
from pathlib import Path
import hashlib
import json
import shutil

ROOT = Path(__file__).resolve().parents[1]
MOBILE = ROOT / 'game/mobile'
ASSETS = MOBILE / 'assets'
shutil.copyfile(ROOT / 'economy.json', ASSETS / 'config/economy.json')
paths = [ASSETS / 'config/economy.json']
for folder in ('progression', 'calibrations', 'challenges', 'events'):
    paths.extend(sorted((ASSETS / folder).glob('*.json')))
manifest = {
    'schema_version': 1,
    'content_version': 'tideglass-native-content-1',
    'economy_version': 'tideglass-economy-1.0.0',
    'environment': 'local_development',
    'files': {str(p.relative_to(MOBILE)): {
        'sha256': hashlib.sha256(p.read_bytes()).hexdigest(),
        'bytes': len(p.read_bytes())} for p in sorted(paths)},
}
# The core's actual version is the stable authority, not an invented label.
import re
core = (ROOT / 'game/core/lib/src/state.dart').read_text()
versions = (ROOT / 'game/core/lib/tideglass_core.dart').read_text()
match = re.search(r"const\s+economyVersion\s*=\s*'([^']+)'", core + versions)
if not match:
    for source in (ROOT / 'game/core/lib/src').glob('*.dart'):
        match = re.search(r"const\s+economyVersion\s*=\s*'([^']+)'", source.read_text())
        if match:
            break
if not match:
    raise SystemExit('Cannot locate the core economy version; no manifest written.')
manifest['economy_version'] = match.group(1)
raw = (json.dumps(manifest, indent=2) + '\n').encode()
(ASSETS / 'config/manifest.json').write_bytes(raw)
digest = hashlib.sha256(raw).hexdigest()
economy = manifest['files']['assets/config/economy.json']['sha256']
(MOBILE / 'lib/bundled_hashes.g.dart').write_text(
    '// Generated by tool/package_content.py; source hashes are not acceptance evidence.\n'
    f"const bundledManifestDigest = '{digest}';\n"
    f"const bundledEconomicDigest = '{economy}';\n")
print(json.dumps({'manifest_sha256':digest,'gameplay_files':len(paths),'economic_sha256':economy}))
